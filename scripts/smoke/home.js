export const home = {
  name: 'home',
  async run(game, assert, env) {
    const { step, until } = env;
    const start = coop => {
      game.scene.getScene('Game').ctx.events.emit('game:quit');
      step(4);
      game.menuNav.play();
      game.menuNav.newGame(1);
      game.menuNav.mode(coop ? 'coop' : 'solo');
      game.menuNav.pick('helena');
      if (coop) game.menuNav.pick('kilian');
      step(4);
      const gs = game.scene.getScene('Game');
      gs.ctx.input.update = () => {};
      return gs;
    };
    let gs = start(false), ctx = gs.ctx;
    assert('a real new game begins inside home in the morning on foot', ctx.world.id === 'home' && ctx.day.phase === 'morning' && ctx.players[0].vehicle === 'foot');
    assert('home has the breakfast table, blue bag, bedroom and labels', gs.home.spots.length === 2 && gs.home.parts.length >= 4);
    const interact = (role, player = 0) => {
      const spot = gs.home.spots.find(o => o.role === role);
      ctx.players[player].teleport(spot.px, spot.py + 20);
      step(2);
      ctx.input.intents[player].interact = true;
      step(1);
      ctx.input.intents[player].interact = false;
      step(2);
    };
    const eaten = [];
    ctx.events.on('breakfast:eaten', e => eaten.push(e));
    ctx.players[0].move.stamina = 0.1;
    interact('breakfast');
    assert('breakfast through interact restores stamina and saves it for this child today', ctx.players[0].stamina === 1 && ctx.state.players[0].morning.breakfast && eaten.length === 1);
    interact('breakfast');
    assert('repeating breakfast does not award it again', eaten.length === 1);
    const ui = game.scene.getScene('UI');
    const before = ui.children.length;
    interact('bag');
    let screen = ctx.screens.top();
    assert('the blue bag opens a freezing drag-and-drop packing screen', screen?.id === 'packing' && ctx.frozen && screen.cards.length === 10);
    const clock = ctx.day.snapshot();
    step(30);
    assert('packing freezes the morning clock', JSON.stringify(clock) === JSON.stringify(ctx.day.snapshot()));
    const required = ctx.home.required();
    assert('the packing screen marks only the items needed by today timetable', screen.cards.every((c, i) => c.text.endsWith(' *') === required.includes(ctx.home.cfg.items[i].id)));
    const card = screen.cards[0];
    const drop = (x, y) => {
      // Manual smoke steps do not render: refresh the camera before projecting a visible drop.
      ui.cameras.main.preRender();
      const pointer = ui.cameras.main.matrix.transformPoint(x, y);
      card.emit('pointerdown');
      card.emit('dragstart');
      card.emit('drag', {}, x, y);
      card.emit('dragend', pointer);
      card.emit('pointerup');
    };
    drop(300, 100);
    assert('dragging a supply into the bag packs it once without the pointer-up undoing it', ctx.state.players[0].bag.join() === 'pencil-case');
    drop(100, 100);
    assert('dragging out removes the packed item', ctx.state.players[0].bag.length === 0);
    card.emit('pointerdown');
    card.emit('pointerup');
    assert('a tap also packs an item for touch players', ctx.state.players[0].bag.join() === 'pencil-case');
    screen.focus = 1;
    ctx.input.intents[0].jump = false;
    step(2);
    ctx.input.intents[0].jump = true;
    step(1);
    ctx.input.intents[0].jump = false;
    step(2);
    assert('confirm through the input intents packs the focused supply', ctx.state.players[0].bag.includes('homework'));
    const lang = ctx.i18n.lang;
    ctx.i18n.set(lang === 'de' ? 'en' : 'de');
    assert('packing switches all item labels and the title with the language', screen.title.text === ctx.t('home.packing', { day: ctx.day.day }) && screen.cards[0].text.includes(ctx.t('home.item.pencil-case')));
    ctx.i18n.set(lang);
    ctx.home.setBag(0, required.filter(id => id !== 'maths-book'));
    screen.retext();
    assert('a forgotten item is visibly listed before leaving', screen.missing.text.includes(ctx.t('home.item.maths-book')));
    screen.close();
    assert('closing packing unfreezes the world and removes every UI object', !ctx.frozen && ui.children.length === before);
    const packed = ctx.state.players[0].bag.join();
    ctx.events.emit('game:quit');
    step(4);
    game.menuNav.play();
    game.menuNav.continueSlot(1);
    step(4);
    gs = game.scene.getScene('Game');
    ctx = gs.ctx;
    ctx.input.update = () => {};
    assert('Continue resumes the morning inside home with breakfast and the saved bag', ctx.world.id === 'home' && ctx.state.players[0].morning.breakfast && ctx.state.players[0].bag.join() === packed);
    interact('bag');
    screen = ctx.screens.top();
    screen.done.emit('pointerdown');
    step(4);
    assert('Ready leaves home, stores the forgotten item and advances to commute', ctx.world.id === 'town' && ctx.day.phase === 'commute' && ctx.state.players[0].morning.packed && ctx.state.players[0].morning.missing.join() === 'maths-book');
    assert('the character gets their starting bike outdoors, not in the kitchen', ctx.players[0].vehicle === 'bike' && gs.bikes.isMounted(0));
    ctx.world.load('school', 'from-town');
    const lesson = ctx.school.next();
    const run = ctx.school.attend();
    step(2);
    const intro = ctx.screens.top();
    assert('forgotten supplies cause a visible localized introduction before the lesson', intro?.id === 'minigameIntroduction' && intro.message.text.includes(ctx.t('home.item.maths-book')) && !game.scene.isActive(ctx.minigames.active.def.scene));
    const readingClock = ctx.day.snapshot();
    step(1000);
    assert('important lesson text stays open indefinitely with the world and lesson clocks stopped', ctx.screens.top() === intro && JSON.stringify(ctx.day.snapshot()) === JSON.stringify(readingClock) && !game.scene.isActive(ctx.minigames.active.def.scene));
    intro.buttons[0].emit('pointerdown');
    step(2);
    const mg = game.scene.getScene(ctx.minigames.active.def.scene);
    until(() => mg.clock.phase === 'play', 450);
    assert('explicit confirmation starts the lesson and removes the reminder without blocking gameplay', !intro.message.scene && mg.clock.phase === 'play');
    ctx.minigames.quit();
    await run;
    step(3);
    assert('quitting the lesson keeps the saved forgotten item without a recorded grade', ctx.school.recordFor(lesson, 0) === undefined && ctx.state.players[0].morning.missing.join() === 'maths-book');

    gs = start(true);
    ctx = gs.ctx;
    interact('breakfast', 1);
    assert('co-op children have independent breakfast progress', !ctx.state.players[0].morning.breakfast && ctx.state.players[1].morning.breakfast);
    interact('bag', 0);
    screen = ctx.screens.top();
    const supplies = ctx.home.required();
    ctx.home.setBag(0, supplies);
    screen.retext();
    screen.finish();
    assert('the first child finishes packing and the second gets their own tab before departure', screen.player === 1 && ctx.world.id === 'home' && ctx.state.players[0].morning.packed && !ctx.state.players[1].morning.packed);
    ctx.input.intents[1].jump = false;
    step(2);
    screen.focus = 0;
    ctx.input.intents[1].jump = true;
    step(1);
    ctx.input.intents[1].jump = false;
    step(2);
    assert('the second child packs through their own intents, independently of the first bag', ctx.state.players[1].bag.join() === 'pencil-case' && ctx.state.players[0].bag.length === supplies.length);
    screen.finish();
    step(4);
    assert('co-op departure keeps both bags and their separate forgotten-item lists', ctx.world.id === 'town' && ctx.state.players[0].morning.missing.length === 0 && ctx.state.players[1].morning.missing.length > 0 && ctx.players[0].vehicle === 'bike' && ctx.players[1].vehicle === 'skateboard');
    const parts = gs.home.parts.length;
    ctx.world.load('home', 'from-town');
    step(2);
    const exit = ctx.map.objects.find(o => o.id === 'home-exit');
    for (const p of ctx.players) p.teleport((exit.x + 1.5) * 16, (exit.y + 0.5) * 16);
    step(4);
    assert('the ordinary home exit door also validates packing and leaves without leaking art', ctx.world.id === 'town' && gs.home.parts.length === parts && ctx.state.players.every(p => p.morning.packed));
    ctx.day.advance('smoke-school');
    ctx.day.advance('smoke-afternoon');
    ctx.day.advance('smoke-evening');
    ctx.day.advance('smoke-next-day');
    assert('the next morning clears old bags and breakfast but keeps character progress', ctx.day.phase === 'morning' && ctx.state.players.every(p => p.bag.length === 0 && !p.morning.breakfast && p.morning.day === ctx.day.day) && ctx.state.players[0].character === 'helena');
  }
};
